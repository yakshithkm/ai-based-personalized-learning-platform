import { useEffect, useState } from 'react';
import { useLocation, useNavigate } from 'react-router-dom';
import { useTranslation } from 'react-i18next';
import { useLocaleFormat } from '../i18n/format';
import { getRecommendation } from '../api/learning';
import ImprovementBanner from '../components/learning/ImprovementBanner';
import { trackProductEvent } from '../utils/productEvents';

const getReadinessLabel = (accuracy = 0, t) => {
  if (accuracy >= 75) return t('summary.readiness.ready');
  if (accuracy >= 50) return t('summary.readiness.improving');
  return t('summary.readiness.notReady');
};

const SessionSummaryPage = () => {
  const { t } = useTranslation();
  const { formatPercent } = useLocaleFormat();
  const navigate = useNavigate();
  const location = useLocation();
  const summary = location.state?.summary;
  const recommendationId = summary?.recommendationId;
  const [learningImpact, setLearningImpact] = useState(null);
  // Text generated by PracticePage travels as English + a translation key; render in the
  // CURRENT language, falling back to the English string when no key is present.
  const keys = summary?.i18nKeys;
  const tr = (field) =>
    keys?.[field] ? t(keys[field], { topic: keys.params?.topic, defaultValue: summary[field] }) : summary?.[field];
  const nextActionLabel = keys?.nextAction ? t(keys.nextAction, { defaultValue: summary?.nextAction?.label }) : summary?.nextAction?.label;

  // After a "practice after learning" set: show how accuracy compares with before the lesson.
  useEffect(() => {
    if (!recommendationId) return undefined;
    let cancelled = false;
    getRecommendation(recommendationId)
      .then((res) => {
        if (!cancelled) setLearningImpact({ title: res.content?.title, effectiveness: res.effectiveness });
      })
      .catch(() => {});
    return () => {
      cancelled = true;
    };
  }, [recommendationId]);

  if (!summary) {
    return (
      <div className="page-grid">
        <section className="panel">
          <h2>{t('summary.title')}</h2>
          <p>{t('summary.none')}</p>
          <button className="solid-btn" onClick={() => navigate('/practice?mode=focus')}>
            {t('summary.startFocus')}
          </button>
        </section>
      </div>
    );
  }

  return (
    <div className="page-grid">
      <section className="panel hero-panel mentor-hero-panel">
        <p className="eyebrow-label">{t('summary.sessionEnd')}</p>
        <h2>{t('summary.mentorJudged')}</h2>
        <p>{t('summary.mentorIntro')}</p>
        {!!summary.earnedXp && <p className="xp-pop summary-xp">{t('summary.reward', { xp: summary.earnedXp })}</p>}
      </section>

      <section className="panel mentor-card mentor-glow-panel">
        <p className="eyebrow-label">{t('summary.mentorFeedback')}</p>
        <h3>{t('summary.mentorSays')}</h3>
        <p className="mentor-summary-text">{tr('mentorFeedback')}</p>
        <div className="mentor-mini-notes">
          <p><strong>{t('summary.score')}:</strong> {t('summary.scoreLine', { accuracy: formatPercent(summary.accuracy), correct: summary.correct, total: summary.total })}</p>
          <p><strong>{t('summary.interpretation')}:</strong> {tr('scoreInterpretation') || getReadinessLabel(summary.accuracy, t)}</p>
          <p><strong>{t('summary.keyPattern')}:</strong> {tr('keyPattern') || t('summary.noFailurePattern')}</p>
        </div>
      </section>

      {learningImpact && <ImprovementBanner title={learningImpact.title} effectiveness={learningImpact.effectiveness} />}

      <section className="panel insight-breakdown-panel">
        <div className="panel-head-row">
          <h3>{t('summary.insightBreakdown')}</h3>
          <span className="subtle-label">{t('summary.insightSub')}</span>
        </div>
        <div className="insight-mini-grid">
          <article className="insight-mini-card">
            <h4>{t('summary.strengths')}</h4>
            {(summary.strengths || []).length ? summary.strengths.map((area) => <p key={area}>{area}</p>) : <p>{t('summary.noStrength')}</p>}
          </article>
          <article className="insight-mini-card">
            <h4>{t('summary.weaknesses')}</h4>
            {(summary.weakAreas || []).length ? summary.weakAreas.map((area) => <p key={area}>{area}</p>) : <p>{t('summary.noWeak')}</p>}
          </article>
          <article className="insight-mini-card">
            <h4>{t('summary.keyPattern')}</h4>
            <p>{tr('keyPattern') || t('summary.noPattern')}</p>
          </article>
        </div>
      </section>

      <section className="panel readiness-panel">
        <div className="readiness-head">
          <div>
            <p className="eyebrow-label">{t('summary.readiness.title')}</p>
            <h3>{getReadinessLabel(summary.accuracy, t)}</h3>
          </div>
          <strong className="readiness-score">{summary.accuracy}</strong>
        </div>
        <div className="readiness-meter">
          <span className="readiness-meter-fill" style={{ width: `${summary.accuracy}%` }} />
        </div>
        <p>{tr('improvementSuggestion')}</p>
      </section>

      <section className="panel next-step-panel dominant-cta-panel">
        <p className="eyebrow-label">{t('summary.nextAction')}</p>
        <h3>{nextActionLabel || t('summary.continueSmart')}</h3>
        <p>{summary.nextAction?.label === 'Take Full Mock Test' ? t('summary.readyForPressure') : t('summary.stayFocused')}</p>
        <div className="feedback-actions">
          <button
            className="solid-btn primary-cta-btn"
            onClick={() => {
              trackProductEvent('next_action_clicked', {
                cta: summary.nextAction?.label || 'continue_smart_practice',
                source: 'session_summary',
                sessionId: summary.sessionId || null,
              });
              navigate(summary.nextAction?.route || '/practice?mode=recommended');
            }}
          >
            {nextActionLabel || t('summary.continueSmart')}
          </button>
          <button className="outline-btn" onClick={() => navigate('/dashboard')}>
            {t('common.backToDashboard')}
          </button>
        </div>
      </section>
    </div>
  );
};

export default SessionSummaryPage;